import sys, numpy as np, torch
sys.path.insert(0, '../beat_this_src')
from beat_this.preprocessing import LogMelSpect
from beat_this.model.postprocessor import Postprocessor

sr = 22050
n = np.arange(sr * 2, dtype=np.float64)
# Deterministic test signal (same formula in the C++ test).
x = (0.5 * np.sin(2 * np.pi * 440.0 * n / sr) + 0.25 * np.sin(2 * np.pi * 3000.0 * n / sr)
     + 0.2 * np.sin(2 * np.pi * 80.0 * n / sr) * (n > 11025)).astype(np.float32)
spec = LogMelSpect()(torch.tensor(x)).numpy()
print('frames', spec.shape)
rows = [0, 7, 40, 100]
with open('ref_logmel.inc', 'w') as f:
    f.write('// Generated by tools/ml/refgen.py from the official Beat This! LogMelSpect (torchaudio).\n')
    f.write('constexpr size_t kRefFrames = %d;\n' % spec.shape[0])
    f.write('constexpr size_t kRefRows[] = {%s};\n' % ','.join(str(r) for r in rows))
    f.write('constexpr float kRefLogMel[][128] = {\n')
    for r in rows:
        f.write('  {' + ','.join('%.8ef' % v for v in spec[r]) + '},\n')
    f.write('};\n')
    f.write('constexpr double kRefSum = %.6f;\n' % float(spec.astype(np.float64).sum()))

# Postprocessing reference: synthetic logits with known peaks.
rng = np.random.default_rng(3)
T = 600
beat = rng.normal(-4, 1.0, T).astype(np.float32)
down = rng.normal(-5, 1.0, T).astype(np.float32)
for i in range(20, T - 20, 25):          # 120 BPM beat grid at 50 fps
    beat[i] = 4.0
    beat[i + 1] = 2.0                    # adjacent weaker peak (dedupe)
for i in range(20, T - 20, 100):         # a downbeat every 4 beats
    down[i] = 3.0
down[12] = 1.0                           # a downbeat peak away from any beat (gets snapped)
pp = Postprocessor('minimal')
b, d = pp(torch.tensor(beat), torch.tensor(down))
print('beats', len(b), 'downbeats', len(d))
with open('ref_post.inc', 'w') as f:
    f.write('// Generated by tools/ml/refgen.py with the official minimal Postprocessor.\n')
    f.write('constexpr size_t kPostT = %d;\n' % T)
    f.write('constexpr float kPostBeatLogits[] = {' + ','.join('%.7ef' % v for v in beat) + '};\n')
    f.write('constexpr float kPostDownLogits[] = {' + ','.join('%.7ef' % v for v in down) + '};\n')
    f.write('constexpr double kPostBeats[] = {' + ','.join('%.6f' % v for v in b) + '};\n')
    f.write('constexpr double kPostDownbeats[] = {' + ','.join('%.6f' % v for v in d) + '};\n')
